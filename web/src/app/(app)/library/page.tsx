"use client";

import { useState } from "react";
import Link from "next/link";
import {
  Archive,
  Search,
  ArrowUpRight,
  ShieldCheck,
  BadgeCheck,
  ChevronRight,
  Download,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { useLanguage } from "@/lib/copy";
import { idr, idrFull } from "@/lib/format";
import { DEMO_ROUTINES, type RoutineArtifactType } from "@/lib/routines-data";

export interface LibraryArtifactItem {
  id: string;
  routineId: string;
  routineTitle: string;
  routineTitleEn: string;
  category: "treasury" | "tax" | "compliance" | "operations";
  timestamp: string;
  status: "success" | "warning" | "error";
  agent: {
    name: string;
    role: string;
    roleEn: string;
  };
  summary: string;
  summaryEn: string;
  statute: string;
  artifactType: RoutineArtifactType;
  payload: Record<string, unknown>;
}

export default function LibraryPage() {
  const { locale } = useLanguage();
  const isEn = locale === "en";

  // Flatten all historical execution runs across routines into an immutable library
  const allArtifacts: LibraryArtifactItem[] = DEMO_ROUTINES.flatMap((routine) =>
    routine.recentExecutions.map((exec) => ({
      id: exec.id,
      routineId: routine.id,
      routineTitle: routine.title,
      routineTitleEn: routine.titleEn,
      category: routine.category,
      timestamp: exec.timestamp,
      status: exec.status,
      agent: {
        name: routine.assignedAgent.name,
        role: routine.assignedAgent.role,
        roleEn: routine.assignedAgent.roleEn,
      },
      summary: exec.findingSummary,
      summaryEn: exec.findingSummaryEn,
      statute: exec.statutoryGrounding,
      artifactType: exec.artifactType,
      payload: exec.artifactPayload,
    }))
  );

  const [searchQuery, setSearchQuery] = useState("");
  const [selectedCategory, setSelectedCategory] = useState<string>("all");
  const [selectedItem, setSelectedItem] = useState<LibraryArtifactItem>(allArtifacts[0]);

  const filteredArtifacts = allArtifacts.filter((item) => {
    const matchesCategory =
      selectedCategory === "all" ? true : item.category === selectedCategory;
    const query = searchQuery.toLowerCase().trim();
    const matchesQuery =
      !query ||
      item.summary.toLowerCase().includes(query) ||
      item.summaryEn.toLowerCase().includes(query) ||
      item.routineTitle.toLowerCase().includes(query) ||
      item.routineTitleEn.toLowerCase().includes(query) ||
      item.statute.toLowerCase().includes(query) ||
      item.agent.name.toLowerCase().includes(query);

    return matchesCategory && matchesQuery;
  });

  const getCategoryBadge = (cat: string) => {
    switch (cat) {
      case "tax":
        return "text-emerald-700 dark:text-emerald-300 bg-emerald-500/10 border-emerald-500/20";
      case "treasury":
        return "text-blue-700 dark:text-blue-300 bg-blue-500/10 border-blue-500/20";
      case "compliance":
        return "text-amber-700 dark:text-amber-300 bg-amber-500/10 border-amber-500/20";
      default:
        return "text-primary bg-primary/10 border-primary/20";
    }
  };

  return (
    <div className="space-y-4">
      {/* Header Bar */}
      <div className="border-b border-border/60 pb-4 flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3">
        <div>
          <div className="flex items-center gap-2">
            <Archive className="size-5 text-primary" />
            <h1 className="text-xl font-semibold tracking-tight text-foreground">
              {isEn ? "Document & Artifact Library" : "Pustaka Dokumen & Bukti"}
            </h1>
          </div>
          <p className="text-xs text-muted-foreground mt-0.5">
            {isEn
              ? "Immutable archive of proofs, tax citations, and executive briefings generated by autonomous agents."
              : "Arsip permanen bukti audit, rujukan statutori pajak, dan ringkasan eksekutif dari agen otonom."}
          </p>
        </div>

        <div className="flex items-center gap-2">
          <Link href="/routines">
            <Button variant="outline" size="sm" className="h-8 text-xs gap-1.5">
              <span>{isEn ? "View Routines" : "Kelola Rutinitas"}</span>
              <ArrowUpRight className="size-3.5" />
            </Button>
          </Link>
        </div>
      </div>

      {/* Filter and Search Bar */}
      <div className="flex flex-col sm:flex-row gap-2.5 items-stretch sm:items-center justify-between">
        <div className="relative flex-1 max-w-md">
          <Search className="absolute left-2.5 top-1/2 -translate-y-1/2 size-3.5 text-muted-foreground" />
          <input
            type="text"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            placeholder={
              isEn
                ? "Search artifacts, statutes, or agents…"
                : "Cari dokumen, pasal regulasi, atau agen…"
            }
            className="w-full bg-card border border-border/70 rounded-lg pl-8 pr-3 py-1.5 text-xs text-foreground placeholder:text-muted-foreground focus:outline-none focus:ring-1 focus:ring-primary"
          />
        </div>

        {/* Category Pills */}
        <div className="flex items-center gap-1.5 overflow-x-auto pb-1 sm:pb-0 text-xs">
          {[
            { id: "all", label: "All Proofs", labelId: "Semua Bukti" },
            { id: "tax", label: "Taxes (PP 55)", labelId: "Pajak (PP 55)" },
            { id: "treasury", label: "Cash & Treasury", labelId: "Kas & Perbankan" },
            { id: "compliance", label: "Licensing & OSS", labelId: "Legalitas OSS" },
          ].map((cat) => (
            <button
              key={cat.id}
              onClick={() => setSelectedCategory(cat.id)}
              className={`px-2.5 py-1 rounded-lg text-xs transition-colors whitespace-nowrap ${
                selectedCategory === cat.id
                  ? "bg-foreground text-background font-medium"
                  : "bg-muted/40 text-muted-foreground hover:text-foreground border border-border/50"
              }`}
            >
              {isEn ? cat.label : cat.labelId}
            </button>
          ))}
        </div>
      </div>

      {/* 2-Pane Library Layout */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-3 items-stretch min-h-[560px]">
        {/* Left Pane: Artifact Documents List (5 cols) */}
        <div className="lg:col-span-5 flex flex-col rounded-xl border border-border/70 bg-card overflow-hidden">
          <div className="p-3 border-b border-border/60 flex items-center justify-between bg-muted/20">
            <span className="text-xs font-semibold text-foreground">
              {isEn ? "Evidence Records" : "Daftar Bukti Permanen"}
            </span>
            <span className="text-[10px] font-mono text-muted-foreground">
              {filteredArtifacts.length} {isEn ? "items" : "arsip"}
            </span>
          </div>

          <div className="p-2 space-y-1.5 flex-1 overflow-y-auto max-h-[640px]">
            {filteredArtifacts.length === 0 ? (
              <div className="p-8 text-center text-xs text-muted-foreground">
                {isEn ? "No artifacts match your query." : "Tidak ada dokumen yang sesuai pencarian."}
              </div>
            ) : (
              filteredArtifacts.map((item) => {
                const isSelected = selectedItem?.id === item.id;

                return (
                  <div
                    key={item.id}
                    onClick={() => setSelectedItem(item)}
                    className={`p-3 rounded-lg border text-left cursor-pointer transition-all ${
                      isSelected
                        ? "border-primary bg-primary/5 shadow-xs"
                        : "border-border/50 hover:bg-muted/20"
                    }`}
                  >
                    <div className="flex items-center justify-between gap-1 mb-1.5">
                      <span
                        className={`text-[10px] font-medium px-1.5 py-0.5 rounded border capitalize ${getCategoryBadge(
                          item.category
                        )}`}
                      >
                        {item.category}
                      </span>
                      <span className="text-[10px] font-mono text-muted-foreground">
                        {item.timestamp}
                      </span>
                    </div>

                    <h4 className="text-xs font-semibold text-foreground line-clamp-1">
                      {isEn ? item.routineTitleEn : item.routineTitle}
                    </h4>

                    <p className="text-[11px] text-muted-foreground line-clamp-2 mt-1 leading-relaxed">
                      {isEn ? item.summaryEn : item.summary}
                    </p>

                    <div className="flex items-center justify-between pt-2 mt-2 border-t border-border/40 text-[10px] text-muted-foreground">
                      <span className="flex items-center gap-1 truncate max-w-[200px]">
                        <ShieldCheck className="size-3 text-primary shrink-0" />
                        <span className="truncate">{item.statute}</span>
                      </span>

                      <span className="text-primary font-medium flex items-center gap-0.5 shrink-0">
                        {isEn ? "Inspect" : "Buka"} <ChevronRight className="size-3" />
                      </span>
                    </div>
                  </div>
                );
              })
            )}
          </div>
        </div>

        {/* Right Pane: Artifact Deep Inspection Canvas (7 cols) */}
        <div className="lg:col-span-7 flex flex-col rounded-xl border border-border/70 bg-card overflow-hidden">
          {selectedItem ? (
            <>
              {/* Card Header */}
              <div className="p-3.5 border-b border-border/60 flex items-center justify-between bg-muted/20">
                <div className="space-y-0.5">
                  <div className="flex items-center gap-2">
                    <span className="text-xs font-semibold text-foreground">
                      {isEn ? selectedItem.routineTitleEn : selectedItem.routineTitle}
                    </span>
                    <Badge variant="outline" className="text-[10px] font-mono">
                      {selectedItem.id}
                    </Badge>
                  </div>
                  <p className="text-[10px] text-muted-foreground">
                    {isEn ? "Audited by" : "Diverifikasi oleh"} {selectedItem.agent.name} (
                    {isEn ? selectedItem.agent.roleEn : selectedItem.agent.role}) &bull;{" "}
                    {selectedItem.timestamp}
                  </p>
                </div>

                <div className="flex items-center gap-1.5">
                  <Button
                    variant="outline"
                    size="sm"
                    onClick={() => window.print()}
                    className="h-7 px-2 text-xs gap-1 border-border/70 text-muted-foreground hover:text-foreground"
                  >
                    <Download className="size-3" />
                    <span>{isEn ? "Print / Export" : "Cetak / Ekspor"}</span>
                  </Button>
                </div>
              </div>

              {/* Artifact Body */}
              <div className="p-4 space-y-4 flex-1 overflow-y-auto">
                {/* Executive Summary Card */}
                <div className="p-3.5 rounded-xl bg-muted/30 border border-border/60 space-y-1.5">
                  <span className="text-[10px] font-mono uppercase text-muted-foreground tracking-wider">
                    {isEn ? "Autonomous Finding & Legal Provenance" : "Ringkasan Temuan & Audit Otonom"}
                  </span>
                  <p className="text-xs text-foreground font-medium leading-relaxed">
                    {isEn ? selectedItem.summaryEn : selectedItem.summary}
                  </p>
                </div>

                {/* Specific Artifact Payloads */}
                <div className="rounded-xl border border-border/60 p-4 space-y-3 bg-background">
                  {/* Artifact Type 1: Cash Briefing */}
                  {selectedItem.artifactType === "cash_briefing" && (
                    <div className="space-y-3">
                      <div className="grid grid-cols-3 gap-2">
                        <div className="p-2.5 rounded-lg bg-muted/30 border border-border/50 text-center">
                          <span className="text-[10px] text-muted-foreground">
                            {isEn ? "Available Cash" : "Saldo Kas Tersedia"}
                          </span>
                          <div className="text-xs font-mono font-bold text-foreground mt-0.5">
                            {idrFull(selectedItem.payload.cashBalance as number)}
                          </div>
                        </div>
                        <div className="p-2.5 rounded-lg bg-muted/30 border border-border/50 text-center">
                          <span className="text-[10px] text-muted-foreground">
                            {isEn ? "Burn Rate" : "Pengeluaran / Hari"}
                          </span>
                          <div className="text-xs font-mono font-bold text-foreground mt-0.5">
                            {idrFull(selectedItem.payload.dailyBurnRate as number)}
                          </div>
                        </div>
                        <div className="p-2.5 rounded-lg bg-muted/30 border border-border/50 text-center">
                          <span className="text-[10px] text-muted-foreground">
                            {isEn ? "Cash Runway" : "Daya Tahan Kas"}
                          </span>
                          <div className="text-xs font-mono font-bold text-emerald-600 dark:text-emerald-400 mt-0.5">
                            {String(selectedItem.payload.runwayDays)} {isEn ? "Days" : "Hari"}
                          </div>
                        </div>
                      </div>

                      <div className="space-y-1.5 pt-1">
                        <span className="text-[10px] text-muted-foreground font-mono uppercase">
                          {isEn ? "Account Breakdown" : "Rincian Akun Kas & Setelmen"}
                        </span>
                        {((selectedItem.payload.lineItems as Array<{ label: string; amount: number }>) || []).map(
                          (item, idx) => (
                            <div key={idx} className="flex justify-between text-xs py-1 border-b border-border/30">
                              <span className="text-muted-foreground">{item.label}</span>
                              <span className="font-mono font-medium">{idrFull(item.amount)}</span>
                            </div>
                          )
                        )}
                      </div>
                    </div>
                  )}

                  {/* Artifact Type 2: Tax Threshold */}
                  {selectedItem.artifactType === "tax_threshold" && (
                    <div className="space-y-3 text-xs">
                      <div className="space-y-1">
                        <div className="flex justify-between text-xs font-medium">
                          <span>{isEn ? "YTD Gross Turnover" : "Omzet Bruto Berjalan"}</span>
                          <span className="font-mono">
                            {idrFull(selectedItem.payload.ytdTurnover as number)} / Rp 500.000.000
                          </span>
                        </div>
                        <div className="w-full bg-muted/50 rounded-full h-2 overflow-hidden border border-border/40">
                          <div
                            className="bg-amber-500 h-full rounded-full"
                            style={{ width: `${selectedItem.payload.thresholdRatio as number}%` }}
                          />
                        </div>
                        <span className="text-[10px] text-amber-600 dark:text-amber-400 font-medium">
                          {String(selectedItem.payload.thresholdRatio)}% {isEn ? "consumed of non-taxable ceiling" : "terpakai dari batas bebas pajak"}
                        </span>
                      </div>

                      <div className="p-2.5 rounded-lg bg-muted/40 text-[11px] text-muted-foreground font-mono leading-relaxed border border-border/50">
                        {String(selectedItem.payload.statuteCite)}
                      </div>
                    </div>
                  )}

                  {/* Artifact Type 3: Reconciliation Table */}
                  {selectedItem.artifactType === "reconciliation_table" && (
                    <div className="space-y-3 text-xs">
                      <div className="grid grid-cols-2 gap-2">
                        <div className="p-2 rounded-lg bg-muted/30 border border-border/50">
                          <span className="text-[10px] text-muted-foreground">{isEn ? "Bank Mutation Match" : "Setoran Bank"}</span>
                          <div className="text-xs font-mono font-bold text-emerald-600 dark:text-emerald-400 mt-0.5">
                            {idrFull(selectedItem.payload.netDisbursed as number)}
                          </div>
                        </div>
                        <div className="p-2 rounded-lg bg-muted/30 border border-border/50">
                          <span className="text-[10px] text-muted-foreground">{isEn ? "Platform Admin Fee" : "Biaya Admin"}</span>
                          <div className="text-xs font-mono font-bold text-muted-foreground mt-0.5">
                            {idrFull(selectedItem.payload.platformFee as number)}
                          </div>
                        </div>
                      </div>

                      <div className="space-y-1 pt-1">
                        <span className="text-[10px] text-muted-foreground font-mono uppercase">
                          {isEn ? "Deterministic Journal Postings" : "Jurnal Otomatis SAK EMKM"}
                        </span>
                        {((selectedItem.payload.journalLines as Array<{ account: string; debit: number; credit: number }>) || []).map(
                          (line, i) => (
                            <div key={i} className="flex justify-between text-[11px] py-1 border-b border-border/30">
                              <span className="text-muted-foreground">{line.account}</span>
                              <span className="font-mono">
                                {line.debit > 0 ? `D: ${idr(line.debit)}` : `C: ${idr(line.credit)}`}
                              </span>
                            </div>
                          )
                        )}
                      </div>
                    </div>
                  )}

                  {/* Artifact Type 4: KBLI Certificate */}
                  {selectedItem.artifactType === "kbli_certificate" && (
                    <div className="space-y-3 text-xs">
                      <div className="flex items-center gap-2.5 p-3 rounded-lg bg-primary/5 border border-primary/20">
                        <BadgeCheck className="size-6 text-primary shrink-0" />
                        <div>
                          <div className="font-semibold text-foreground text-xs">
                            {String(selectedItem.payload.kbliCode)} &bull; {String(selectedItem.payload.riskLevel)}
                          </div>
                          <div className="text-[11px] text-muted-foreground">
                            {String(selectedItem.payload.kbliTitle)}
                          </div>
                        </div>
                      </div>

                      <div className="space-y-1.5 pt-1">
                        <span className="text-[10px] text-muted-foreground font-mono uppercase">
                          {isEn ? "OSS Legal Requirements Satisfied" : "Kepatuhan Regulasi OSS Terpenuhi"}
                        </span>
                        {((selectedItem.payload.legalRequirements as Array<{ req: string; status: string }>) || []).map(
                          (r, i) => (
                            <div key={i} className="flex justify-between text-[11px] py-1 border-b border-border/30">
                              <span className="text-muted-foreground">{r.req}</span>
                              <span className="font-medium text-emerald-600 dark:text-emerald-400">{r.status}</span>
                            </div>
                          )
                        )}
                      </div>
                    </div>
                  )}
                </div>

                {/* Grounding & Agent Handoff Footer */}
                <div className="flex items-center justify-between p-3 rounded-xl bg-muted/30 border border-border/50 text-[11px]">
                  <span className="flex items-center gap-1.5 text-muted-foreground">
                    <ShieldCheck className="size-3.5 text-primary shrink-0" />
                    <span>{selectedItem.statute}</span>
                  </span>

                  <Link
                    href="/agents"
                    className="flex items-center gap-1 text-primary hover:underline font-medium"
                  >
                    <span>{isEn ? "Consult Agent Lead" : "Konsultasi ke Agen"}</span>
                    <ArrowUpRight className="size-3" />
                  </Link>
                </div>
              </div>
            </>
          ) : (
            <div className="p-8 text-center text-xs text-muted-foreground m-auto">
              {isEn ? "Select an evidence record to inspect." : "Pilih bukti dokumen untuk diperiksa."}
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
